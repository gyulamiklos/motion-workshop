"""Hungarian voiceover with MOSS-TTS-Local-Transformer-v1.5, one WAV per line, run on this machine (nothing leaves it).

Usage: tools/tts/.venv-moss/bin/python tools/tts/moss_say.py <lines.json> <out dir> [--voice male|female|none] [--takes 3]
Normally called through tools/tts/say.py, which picks this engine when it is set up (tools/tts/setup.sh).

Each line is spoken in a fixed reference voice (voices-moss/<voice>.wav, itself generated by MOSS), so the speaker
stays the same across a film; --voice none lets the model invent a voice per line (only for making new reference
voices). The model sometimes stalls or hesitates mid-sentence, so every line gets several takes and the best one is
kept: Whisper transcribes each take, and the score is the word error rate against the script plus penalties for long
pauses inside a sentence and for speech far slower than normal. The scores go to <out dir>/takes.json.
"""
import argparse
import json
import pathlib
import re
import subprocess
import time
import unicodedata

import numpy as np
import soundfile as sf
import torch
import torchaudio


def _load(path, *a, **k):
    """torchaudio's default backend (torchcodec) needs FFmpeg shared libraries; read reference audio with soundfile."""
    data, sr = sf.read(str(path), dtype="float32", always_2d=True)
    return torch.from_numpy(data.T.copy()), sr


torchaudio.load = _load
from faster_whisper import WhisperModel  # noqa: E402
from huggingface_hub import snapshot_download  # noqa: E402
from transformers import AutoModel, AutoProcessor  # noqa: E402

HERE = pathlib.Path(__file__).resolve().parent
MODEL = "OpenMOSS-Team/MOSS-TTS-Local-Transformer-v1.5"
REVISION = "be7766a6735b98bd793f7c79fb720b4d0f5d13b8"  # pinned; setup.sh downloads these
CODEC = "OpenMOSS-Team/MOSS-Audio-Tokenizer-v2"
CODEC_REVISION = "f6e20e543b33d2c252a7ef71bdf8aa71e5ff9169"
LOUDNESS = "loudnorm=I=-15:TP=-1.5:LRA=11"  # same speech loudness as the Piper engine (EBU R128)
CHARS_PER_S = 14  # Hungarian narration: letters and spaces a second
PAUSE = 0.45  # a silence longer than this inside a sentence sounds like hesitation
SAMPLING = dict(do_sample=True, audio_temperature=1.7, audio_top_p=0.8, audio_top_k=25, audio_repetition_penalty=1.0)


def words(s):
    return re.sub(r"[^\w\s]", " ", unicodedata.normalize("NFC", s.lower())).split()


def wer(ref, hyp):
    d = list(range(len(hyp) + 1))
    for i, r in enumerate(ref, 1):
        prev, d[0] = d[0], i
        for j, h in enumerate(hyp, 1):
            prev, d[j] = d[j], min(d[j] + 1, d[j - 1] + 1, prev + (r != h))
    return d[-1] / max(len(ref), 1)


def extra_pauses(mono, sr, text):
    """Silences longer than PAUSE between the first and last voiced frame, beyond one per sentence end in the text."""
    hop = int(sr * 0.02)
    rms = np.sqrt(np.convolve(mono ** 2, np.ones(hop) / hop, mode="same"))[::hop]
    voiced = rms > max(rms.max() * 0.03, 1e-4)
    idx = np.flatnonzero(voiced)
    if idx.size == 0:
        return 99
    long, n = 0, 0
    for v in voiced[idx[0]: idx[-1] + 1]:
        if v:
            long += n * 0.02 > PAUSE
            n = 0
        else:
            n += 1
    return max(0, long - len(re.findall(r"[.!?:]\s", text)))


def score_take(whisper, audio, sr, text):
    mono = audio.mean(axis=0)
    heard = " ".join(s.text.strip() for s in whisper.transcribe(
        torchaudio.functional.resample(torch.from_numpy(mono), sr, 16000).numpy(), language="hu", beam_size=5)[0])
    e, p = wer(words(text), words(heard)), extra_pauses(mono, sr, text)
    duration = audio.shape[-1] / sr
    stretch = max(0.0, duration / (len(text) / CHARS_PER_S) - 1.3)
    return {"wer": round(e, 3), "extra_pauses": p, "duration": round(duration, 2), "stretch": round(stretch, 2),
            "score": round(e + 0.3 * p + stretch, 3), "heard": heard}


def load_model(path):
    """The whole model on the GPU when it fits (~9 GB in bf16); otherwise the GPU keeps what fits and the rest runs
    from RAM (works on 8 GB, about 7 s of compute for 1 s of speech). 8- and 4-bit loading do not apply to this model."""
    if not torch.cuda.is_available():
        raise SystemExit("MOSS needs an NVIDIA GPU; use --engine piper on this machine")
    kw = dict(trust_remote_code=True, attn_implementation="sdpa", dtype=torch.bfloat16)
    total = torch.cuda.get_device_properties(0).total_memory / 2**30
    if total >= 11:
        return AutoModel.from_pretrained(path, **kw).to("cuda").eval()
    return AutoModel.from_pretrained(path, device_map="auto", max_memory={0: f"{total - 1.5:.1f}GiB", "cpu": "64GiB"}, **kw).eval()


def normalize(path: pathlib.Path) -> None:
    """Mono, 48 kHz, -15 LUFS with a -1.5 dBTP ceiling (ffmpeg loudnorm), in place."""
    tmp = path.with_suffix(".norm.wav")
    subprocess.run(["ffmpeg", "-nostdin", "-v", "error", "-y", "-i", str(path), "-af", LOUDNESS, "-ac", "1", "-ar", "48000", str(tmp)], check=True)
    tmp.replace(path)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("lines")
    ap.add_argument("out")
    ap.add_argument("--voice", default="male", help="a reference in voices-moss/ (male, female), or none")
    ap.add_argument("--takes", type=int, default=3, help="takes per line; the best is kept")
    args = ap.parse_args()

    ref = None
    if args.voice != "none":
        ref = HERE / "voices-moss" / f"{args.voice}.wav"
        if not ref.exists():
            raise SystemExit(f"no reference voice {ref}; voices: {', '.join(p.stem for p in (HERE / 'voices-moss').glob('*.wav'))}")
    lines = json.loads(pathlib.Path(args.lines).read_text(encoding="utf-8"))
    out = pathlib.Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    torch.backends.cuda.enable_cudnn_sdp(False)  # the cuDNN SDPA backend is broken for this model (MOSS README)
    codec = snapshot_download(CODEC, revision=CODEC_REVISION)
    path = snapshot_download(MODEL, revision=REVISION)  # remote code does not pass "revision" on, so load the pinned folder
    processor = AutoProcessor.from_pretrained(path, trust_remote_code=True, codec_path=codec)  # codec stays on the CPU
    model = load_model(path)
    whisper = WhisperModel("large-v3-turbo", device="cpu", compute_type="int8")
    sr = processor.model_config.sampling_rate

    manifest = {"voice": f"moss-tts-local-v1.5:{args.voice}", "lines": {}}
    report = {}
    for line in lines:
        message = processor.build_user_message(text=line["text"], language="Hungarian", **({"reference": [str(ref)]} if ref else {}))
        batch = processor([[message]], mode="generation")
        takes = []
        for k in range(args.takes):
            torch.manual_seed(1000 + k)
            t = time.time()
            with torch.no_grad():
                o = model.generate(input_ids=batch["input_ids"].to("cuda"), attention_mask=batch["attention_mask"].to("cuda"),
                                   max_new_tokens=4096, **SAMPLING)
            decoded = [m for m in processor.decode(o) if m is not None]
            if not decoded:
                continue
            audio = decoded[0].audio_codes_list[0].detach().cpu().float().numpy()
            audio = audio[None] if audio.ndim == 1 else audio
            takes.append((score_take(whisper, audio, sr, line["text"]) | {"take": k, "seconds": round(time.time() - t, 1)}, audio))
        if not takes:
            raise SystemExit(f"{line['id']}: no audio generated")
        takes.sort(key=lambda x: x[0]["score"])
        best, audio = takes[0]
        path = out / f"{line['id']}.wav"
        sf.write(str(path), audio.T, sr)
        normalize(path)
        duration = sf.info(str(path)).duration
        manifest["lines"][line["id"]] = {"file": path.name, "duration": round(duration, 3), "text": line["text"]}
        report[line["id"]] = [s for s, _ in takes]
        print(f"{line['id']}: {duration:.2f}s (take {best['take']}, score {best['score']}, heard: {best['heard']})", flush=True)
    (out / "voice.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    (out / "takes.json").write_text(json.dumps(report, ensure_ascii=False, indent=1), encoding="utf-8")


if __name__ == "__main__":
    main()
